#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const VIDEOS_FILE = path.join(ROOT, 'projects/reiki-yggdrasil/data/youtube-videos.json');
const COURSES_FILE = path.join(ROOT, 'projects/reiki-yggdrasil/data/youtube-courses.json');
const DIONYSUS_KEYWORDS = ['дионис', 'dionysus', 'мистерии диониса', 'мистерии греции. дионис', 'вакх', 'bacchus', 'вакханалии', 'сатиры', 'менады', 'сатиры и менады', 'музыка диониса', 'любовь и друзья'];

function today() {
  return new Date().toISOString().slice(0, 10);
}

function readJson(filePath) {
  return JSON.parse(fs.readFileSync(filePath, 'utf8'));
}

function writeJson(filePath, data) {
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function classify(text = '') {
  const normalized = String(text).toLowerCase();
  const topics = new Set();
  if (DIONYSUS_KEYWORDS.some((keyword) => normalized.includes(keyword))) topics.add('Дионис');
  if (normalized.includes('мистерии греции')) topics.add('Мистерии Греции');
  return [...topics];
}

const videos = readJson(VIDEOS_FILE).map((video) => {
  const detectedTopics = classify(`${video.title}\n${video.description}\n${(video.detectedTopics || []).join(' ')}`);
  const isDionysus = detectedTopics.includes('Дионис');
  return {
    ...video,
    detectedTopics,
    courseSlug: isDionysus ? 'misterii-dionisa' : (video.courseSlug || 'needs verification'),
    courseTitle: isDionysus ? 'Мистерии Диониса' : (video.courseTitle || 'needs verification'),
    manualReviewStatus: video.manualReviewStatus || 'needs verification',
    lastCheckedAt: video.lastCheckedAt || today()
  };
});

const courses = readJson(COURSES_FILE);
const dionysusIds = videos.filter((video) => video.courseSlug === 'misterii-dionisa').map((video) => video.videoId);
const existingCourse = courses.find((course) => course.courseSlug === 'misterii-dionisa');
const record = {
  courseSlug: 'misterii-dionisa',
  courseTitle: 'Мистерии Диониса',
  project: 'reiki-yggdrasil',
  channelSlugs: ['shamanic-academy'],
  topics: ['Дионис', 'Dionysus', 'Вакх', 'Bacchus', 'вакханалии', 'сатиры', 'менады', 'Мистерии Греции'],
  videoIds: [...new Set(dionysusIds)],
  status: 'needs verification',
  lastCheckedAt: today(),
  notes: existingCourse?.notes || 'Generated by scripts/youtube/classify-youtube-videos.mjs.'
};
const index = courses.findIndex((course) => course.courseSlug === record.courseSlug);
if (index >= 0) courses[index] = { ...courses[index], ...record };
else courses.push(record);

writeJson(VIDEOS_FILE, videos);
writeJson(COURSES_FILE, courses);
console.log(JSON.stringify({
  ok: true,
  videos: videos.length,
  dionysusVideos: dionysusIds.length,
  courses: courses.length
}, null, 2));
